#!/usr/bin/env python3
"""Generate interop/ref_typed_gen_test.go: a table of every typed OCPP message
(v16, v201, v21 profiles) so the interop suite can exercise gocpp's typed API
for all actions, not only the raw one. Run from the repository root:

    python3 scripts/gen-interop-typed.py > interop/ref_typed_gen_test.go
"""
import re

versions = [("1.6", "v16"), ("2.0.1", "v201"), ("2.1", "v21")]
print("// Code generated by scripts/gen-interop-typed.py. DO NOT EDIT.")
print()
print("//go:build interop")
print()
print("package interop")
print()
print("import (")
for _, d in versions:
    print(f'\t{d}p "github.com/shiv3/gocpp/{d}/profiles"')
print(")")
print()
print("var typedTable = map[string]map[string]typedMsg{")
for ver, d in versions:
    import glob
    names = []
    for f in sorted(glob.glob(f"{d}/profiles/*.go")):
        src = open(f).read()
        names += re.findall(r"^var (\w+) = ocppj\.Message\[", src, re.M)
    print(f'\t"{ver}": {{')
    for n in sorted(names):
        print(f'\t\t"{n}": mkTyped({d}p.{n}),')
    print("\t},")
print("}")
